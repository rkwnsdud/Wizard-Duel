// 방의 진행 단계. 스냅샷으로 두 클라이언트에 알린다.
// 한 판 안에서는 앞으로만 넘어가고, 결과를 보여 준 뒤에는 다음 판(Round + 1)의 Lobby로 돌아간다.
public enum LobbyPhase : byte
{
    // 설정을 바꾸고 상대를 기다린다.
    Lobby,
    // 시작이 승인되어 서버와 두 클라이언트가 맵을 만들고 지문을 맞춘다. 설정을 더 바꿀 수 없다.
    Preparing,
    // 두 플레이어가 소환되고 전투 입력이 켜졌다.
    Battle,
    // 한 명이 쓰러져 승자가 정해졌다. 입력을 멈추고 승자를 잠깐 보여 준 뒤 로비로 돌아간다.
    Result
}
